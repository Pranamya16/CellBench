"""Build self-contained Kaggle kernels (one script each) that run the confirmation tasks for chosen models.

    python cellbench/kaggle/build_kernel.py <out_dir> --models mlp_report mlp_rich mlp_cells [--tag cb-mlp-dry]

Writes <out_dir>/<account>/{script.py, kernel-metadata.json} for each of the four accounts; the tasks are dealt out
round-robin so every kernel gets a mix. The script embeds the generator, features, models, evaluation code, the
population table and the config, so the kernel needs no dataset and no internet.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "cellbench"))
import tasks as T

ACCOUNTS = ["pranamyadeshpande", "hunter69xffff", "kakashi26", "deshpandepranamya"]
SOURCES = ["cellbench/generator.py", "cellbench/features.py", "cellbench/gating.py", "cellbench/models.py", "cellbench/evaluate.py",
           "data/population_table.csv", "configs/experiment.json"]

TEMPLATE = r'''# Auto-generated by cellbench/kaggle/build_kernel.py. Do not edit; rebuild instead.
import os, sys, time, warnings
os.environ["OMP_NUM_THREADS"] = "1"
warnings.filterwarnings("ignore")
from pathlib import Path

FILES = __FILES__
TASKS = __TASKS__
MODELS = __MODELS__
KERNEL = __KERNEL__

PROJ = Path(os.environ.get("CB_PROJ", "/kaggle/working/proj"))
OUT = Path(os.environ.get("CB_OUT", "/kaggle/working/results.csv"))
LIMIT = int(os.environ.get("CB_LIMIT", "0"))
for rel, text in FILES.items():
    p = PROJ / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)
sys.path.insert(0, str(PROJ / "cellbench"))

import pandas as pd
import torch
import generator as G
import evaluate as E

torch.set_num_threads(1)
print("kernel", KERNEL, "| tasks", len(TASKS), "| models", MODELS, "| torch", torch.__version__, "| cpus", os.cpu_count(),
      "| cuda", torch.cuda.is_available(), torch.cuda.get_device_name(0) if torch.cuda.is_available() else "", flush=True)
gen = G.Generator()
t0, first = time.time(), True
for i, (s, shuffle, tag) in enumerate(TASKS[: LIMIT or None]):
    df = pd.DataFrame(E.run_cohort(s, gen, models=MODELS, shuffle_labels=shuffle, tag=tag))
    df["kernel"] = KERNEL
    df.to_csv(OUT, mode="a" if not first else "w", header=first, index=False)
    first = False
    print(f"task {i + 1}/{len(TASKS)} done at {time.time() - t0:.0f}s", flush=True)
print("DONE", flush=True)
'''


def sweep_tasks(plan="full", extra_null_seeds=range(201, 216)):
    """The sweep: every cohort of the manifest, plus extra no-signal cohorts (spare seeds) for a bigger null check."""
    import pandas as pd
    rows = json.loads(pd.read_csv(ROOT / "data" / "synthetic" / f"manifest_{plan}.csv").to_json(orient="records"))
    tasks = [(r, False, "no_signal" if r["signal_type"] == "none" else "signal") for r in rows]
    n = rows[0]["patients_per_group"]
    for noise in ["independent", "shared"]:
        for seed in extra_null_seeds:
            tasks.append((dict(seed=seed, noise=noise, patients_per_group=n, signal_type="none", affected_fraction=0.0,
                               shift_size=0.0, cohort_id=f"extra_null_{noise}_{seed}"), False, "extra_null"))
    return tasks


def build(out_dir, models, tag, tasks=None, kernels=4, accounts=ACCOUNTS, seeds=(101, 102, 103), n=300, gpu=False):
    files = {rel: (ROOT / rel).read_text() for rel in SOURCES}
    tasks = tasks or T.confirmation_tasks(seeds, n)
    out = Path(out_dir)
    for k in range(kernels):
        acct = accounts[k % len(accounts)]
        mine = tasks[k::kernels]
        d = out / f"{acct}_{k + 1}"
        d.mkdir(parents=True, exist_ok=True)
        slug = f"{tag}-{k + 1}"
        script = (TEMPLATE.replace("__FILES__", repr(files)).replace("__TASKS__", repr(mine))
                  .replace("__MODELS__", repr(list(models))).replace("__KERNEL__", repr(f"{acct}/{slug}")))
        (d / "script.py").write_text(script)
        (d / "kernel-metadata.json").write_text(json.dumps({
            "id": f"{acct}/{slug}", "title": slug, "code_file": "script.py", "language": "python", "kernel_type": "script",
            "is_private": "true", "enable_gpu": "true" if gpu else "false", "enable_tpu": "false", "enable_internet": "false",
            "dataset_sources": [], "competition_sources": [], "kernel_sources": [], "model_sources": []}, indent=2))
        print(f"{acct}/{slug}: {len(mine)} tasks -> {d}")


FINAL_TEMPLATE = r'''# Auto-generated by cellbench/kaggle/build_kernel.py (final models). Do not edit; rebuild instead.
import os, sys, warnings
os.environ["OMP_NUM_THREADS"] = "4"
os.environ["CB_PAIR"] = __PAIR__
os.environ["CB_SMOKE"] = __SMOKE__
os.environ.setdefault("CB_OUT", "/kaggle/working/final")
warnings.filterwarnings("ignore")
from pathlib import Path
FILES = __FILES__
PROJ = Path(os.environ.get("CB_PROJ", "/kaggle/working/proj"))
for rel, text in FILES.items():
    p = PROJ / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)
sys.path.insert(0, str(PROJ / "cellbench"))
import final_models
final_models.main()
'''


def build_final(out_dir, pair, smoke, account="pranamyadeshpande", slug=None):
    """One self-contained GPU kernel that trains, calibrates, tests and saves the final models of one pair."""
    files = {rel: (ROOT / rel).read_text() for rel in SOURCES + ["cellbench/final_models.py"]}
    slug = slug or f"cb-final-{pair}{'-smoke' if smoke else ''}"
    d = Path(out_dir) / slug
    d.mkdir(parents=True, exist_ok=True)
    (d / "script.py").write_text(FINAL_TEMPLATE.replace("__FILES__", repr(files)).replace("__PAIR__", repr(pair))
                                 .replace("__SMOKE__", repr("1" if smoke else "0")))
    (d / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{account}/{slug}", "title": slug, "code_file": "script.py", "language": "python", "kernel_type": "script",
        "is_private": "true", "enable_gpu": "true", "enable_tpu": "false", "enable_internet": "false",
        "dataset_sources": [], "competition_sources": [], "kernel_sources": [], "model_sources": []}, indent=2))
    print(f"{account}/{slug} -> {d}")
    return d


if __name__ == "__main__" and "--final" in sys.argv:
    a = sys.argv[1:]
    build_final(a[0], a[a.index("--final") + 1], "--smoke" in a)
elif __name__ == "__main__":
    a = sys.argv[1:]
    models = []
    i = a.index("--models") + 1
    while i < len(a) and not a[i].startswith("--"):
        models.append(a[i]); i += 1
    tag = a[a.index("--tag") + 1] if "--tag" in a else "cb-mlp-dry"
    gpu = "--gpu" in a
    kernels = int(a[a.index("--kernels") + 1]) if "--kernels" in a else 8
    if "--tuning-and-sweep" in a:   # 72 tuning cohorts (seeds 101-103) first in each kernel's list, then the 210 sweep cohorts
        tuning = T.confirmation_tasks((101, 102, 103), 300)
        build(a[0], models, tag, tasks=tuning + sweep_tasks("full"), kernels=kernels, gpu=gpu)
    elif "--sweep" in a:
        build(a[0], models, tag, tasks=sweep_tasks(a[a.index("--sweep") + 1]), kernels=kernels, gpu=gpu)
    else:
        build(a[0], models, tag, gpu=gpu)
